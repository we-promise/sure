class RecurringTransaction
  # Turns a purchase into an installment plan.
  #
  # The plan is a Bills installment series: the monthly charges are
  # occurrences, not entries, so nothing is written into the ledger until a
  # charge actually lands. The interest split comes from the loan layer's
  # amortisation schedule, so a plan and a loan cannot drift apart: same
  # engine, same rounding, same payment split.
  #
  # The purchase the plan takes over stops counting: it leaves the budget and
  # the balance, and the plan's charges take its place. A purchase on a
  # linked account is left alone -- there the provider's own transactions are
  # the truth, and a plan on top of them would count the same money twice.
  class InstallmentPlan
    attr_reader :family, :user, :entry, :interest_rate, :term_months,
                :requested_due_on, :interest_category

    def initialize(family:, user:, entry:, interest_rate:, term_months:,
                   first_due_on: nil, interest_category_id: nil)
      @family = family
      @user = user
      @entry = entry
      @interest_rate = interest_rate
      @term_months = term_months
      @requested_due_on = first_due_on
      @interest_category_id = interest_category_id
      @interest_category = family.categories.find_by(id: interest_category_id) if interest_category_id.present?
    end

    # The unsaved series, with every problem attached to it. Callers read
    # #errors rather than exceptions, the way a form does.
    def build
      # Build the carrier directly: going through the association would leave
      # an invalid record in family.recurring_transactions for the rest of the
      # request.
      series = RecurringTransaction.new(family: family)
      apply_problems(series)
      return series if series.errors.any?

      family.recurring_transactions.new(series_attributes)
    end

    # Builds the plan and, when it saves, hands the purchase over to it.
    def call
      return build if entry.blank?

      result = nil
      saved = false
      Entry.transaction do
        # The same advisory lock the allocator and the mark-recurring path use,
        # so a plan and an ordinary series cannot both claim this purchase.
        Allocator.lock_entry!(entry)
        entry.lock!
        series = build
        if series.errors.any?
          result = series
        else
          saved = RecurringTransaction::DeclaredBill.save(series)
          if saved
            entry.update!(excluded: true)
            entry.sync_account_later
            result = series
          else
            result = series
          end
        end
      end

      # Occurrences are generated by an after_commit callback, so the stamp
      # has to run once that transaction has committed.
      result.stamp_financed_instalment_amounts! if saved && result&.persisted?
      result
    end

    # True when this purchase can become a plan. The UI uses this to decide
    # whether to offer the action; #call repeats the checks on save.
    def eligible?
      entry.present? && standard_purchase? && manual_account? && writable_account? && !already_planned?
    end

    # The loan layer's schedule for this plan: what each instalment pays, and
    # how much of it is interest.
    def schedule
      @schedule ||= Loan::AmortizationSchedule.new(
        principal: principal,
        annual_rate: annual_rate,
        term_months: term_months,
        start_date: start_date,
        currency: currency
      )
    end

    private
      def series_attributes
        {
          name: entry&.name,
          merchant: merchant,
          category: category,
          account: account,
          currency: currency,
          amount: schedule.periodic_payment.amount,
          bill_type: "installment",
          end_mode: "after_count",
          end_after_count: term_months,
          anchor_date: first_due_on,
          expected_day_of_month: first_due_on.day,
          last_occurrence_date: first_due_on,
          next_expected_date: first_due_on,
          status: "active",
          manual: true,
          occurrence_count: 0,
          financed_principal_amount: principal,
          financed_interest_rate: annual_rate,
          financed_interest_category_id: interest_category&.id,
          financed_source_entry_id: entry&.id,
          # Two plans for two purchases at the same merchant would otherwise
          # collide on the identity index, so each plan carries its own source.
          dedup_scope: "installment-#{entry&.id}-#{SecureRandom.hex(4)}"
        }
      end

      def apply_problems(series)
        series.errors.add(:base, :installment_plan_missing_purchase) if entry.blank?
        series.errors.add(:base, :installment_plan_purchase_not_standard) unless standard_purchase?
        series.errors.add(:base, :installment_plan_purchase_not_writable) unless writable_account?
        series.errors.add(:base, :installment_plan_purchase_not_manual) unless manual_account?
        series.errors.add(:base, :installment_plan_purchase_already_planned) if already_planned?
        series.errors.add(:base, :installment_plan_invalid_rate) unless valid_rate?
        series.errors.add(:base, :installment_plan_invalid_term) unless valid_term?
        series.errors.add(:base, :installment_plan_invalid_first_due) unless valid_first_due?
        if @interest_category_id.present? && interest_category.blank?
          series.errors.add(:base, :installment_plan_invalid_interest_category)
        end
        return if series.errors.any?

        unless FinancingTerms.positive_schedule?(schedule)
          series.errors.add(:base, :installment_plan_invalid_amount)
        end
      end

      def stamp_instalment_amounts(series)
        series.stamp_financed_instalment_amounts!
      end

      def transaction
        @transaction ||= entry.entryable if entry&.entryable.is_a?(Transaction)
      end

      # A purchase the plan can take over: an ordinary expense, still counted,
      # on an account the user can write.
      def standard_purchase?
        return false if entry.blank? || entry.excluded?
        return false if entry.split_child? || entry.split_parent?
        return false unless transaction.present?
        return false unless transaction.kind == "standard"

        principal.positive?
      end

      def writable_account?
        return false if account.blank?

        Account.writable_by(user).where(id: account.id).exists?
      end

      # A linked account's transactions are the provider's truth. A plan on top
      # of them would count the same money twice: once from the provider and
      # once from the plan.
      def manual_account?
        account.present? && account.manual? && account.accountable_type == "CreditCard"
      end

      def already_planned?
        return false if entry.blank?

        family.recurring_transactions
              .where(financed_source_entry_id: entry.id)
              .where(status: %w[active paused])
              .exists?
      end

      def valid_rate?
        FinancingTerms.valid_rate?(annual_rate)
      end

      def valid_term?
        FinancingTerms.valid_term?(term_months)
      end

      def valid_first_due?
        FinancingTerms.valid_first_due?(first_due_on, purchase_date: entry&.date)
      end

      def account
        entry&.account
      end

      def merchant
        transaction&.merchant
      end

      def category
        transaction&.category
      end

      def currency
        entry&.currency.presence || account&.currency.presence || family.currency
      end

      def principal
        (entry&.amount || 0).to_d
      end

      def annual_rate
        FinancingTerms.parse_rate(interest_rate)
      end

      # The plan is written from the purchase date, so the first instalment
      # falls a month after it and the loan engine counts a period of
      # interest for each one.
      def start_date
        first_due_on.prev_month
      end

      def first_due_on
        @first_due_on ||= requested_due_on || [ (entry&.date || Date.current).next_month, Date.current ].max
      end
  end
end
