# Per-family overrides for the built-in AI prompts, editable from
# /settings/ai_prompts so tuning them no longer needs a fork + redeploy.
#
# Every override is stored in one jsonb column, one per feature (section 8.3), and resolved
# where the prompt is chosen: Ai::Prompt for categorization and merchant detection,
# `Assistant::Configurable#default_instructions` for chat. An override replaces the
# instructions as plain text and is never compiled. A blank value is deleted on save, so
# clearing a field *is* resetting it.
module Family::AiPromptable
  extend ActiveSupport::Concern

  # Overrides are sent to the provider on every call, so an unbounded value is a
  # cost problem, not just a storage one. Generous next to the ~4KB defaults.
  MAX_LENGTH = 20_000

  # Which feature each generation key overrides (Ai::Prompt::OVERRIDES the other way).
  FEATURES = { categorize_transactions: :categorize, detect_merchants: :detect_merchants }.freeze

  # Each key's stock text, lazily. A generation key's default is the prompt this install's route
  # sends (the simplified one on a custom OpenAI-compatible server, Anthropic's own on
  # Anthropic), so editing it never swaps a small local model's terse rules for a prompt
  # written for GPT-4.
  DEFAULTS = {
    chat_system: ->(_family) { Assistant::Configurable::STATIC_INSTRUCTIONS },
    categorize_transactions: ->(family) { RubyLLM.render_prompt("#{family.ai_prompt_folder(:categorize_transactions)}/instructions") },
    detect_merchants: ->(family) { RubyLLM.render_prompt("#{family.ai_prompt_folder(:detect_merchants)}/instructions") },
    # The visible first chat message of "Dig in with AI", not instructions.
    insight_dig_in: ->(_family) { I18n.t("insights.dig_in.prompt") }
  }.freeze

  KEYS = DEFAULTS.keys.freeze

  # The simplified prompts for custom servers also ask for these keys in a per-request message
  # an override cannot replace, so a missing one rarely breaks parsing by itself. It stays the
  # cheapest signal that someone deleted the example block, so the editor says so instead of
  # rejecting the save. The other prompts get their shape from the schema.
  WRAPPER_KEYS = { categorize_transactions: "categorizations", detect_merchants: "merchants" }.freeze

  # Left by the key collapse's migration when a family had two different overrides for one
  # feature; the prompts page shows the dropped one until the next save.
  DROPPED_CATEGORY = "ai_prompt_override_dropped".freeze

  # Attribute names generated by `store_accessor` below — the form fields and the
  # controller's permitted params.
  FIELDS = KEYS.map { |key| :"ai_prompt_#{key}" }.freeze

  included do
    store_accessor :ai_prompt_overrides, *KEYS, prefix: :ai_prompt

    # Assigned rather than mutated in place so the jsonb attribute is
    # unambiguously dirty when only blanks were submitted (a reset).
    before_save { self.ai_prompt_overrides = ai_prompt_overrides.to_h.compact_blank }

    validate :validate_ai_prompt_overrides_schema

    validates *FIELDS,
      length: {
        maximum: MAX_LENGTH,
        message: ->(_object, _data) {
          I18n.t("errors.messages.too_long", count: MAX_LENGTH.to_fs(:delimited))
        }
      },
      allow_blank: true
  end

  # The family's override for `key`, or nil when it runs the default.
  def ai_prompt(key)
    ai_prompt_overrides[key.to_s].presence
  end

  def ai_prompt_default(key)
    DEFAULTS.fetch(key.to_sym).call(self)
  end

  # The prompt folder this family's route sends for a generation key: its first LLM entry's
  # prompt, else the feature's default.
  def ai_prompt_folder(key)
    feature = FEATURES.fetch(key.to_sym)
    route = Ai.plan(feature, family: self)&.routes&.find { !_1.judge? }
    route&.prompt.presence || key.to_s
  end

  # True when this install sends a prompt carrying a wrapper key and the family's override
  # dropped it. Advisory only, never a validation error.
  def ai_prompt_format_risk?(key)
    wrapper = WRAPPER_KEYS[key.to_sym]
    return false unless wrapper && ai_prompt_folder(key).end_with?("_simple")

    override = ai_prompt(key)
    override.present? && override.exclude?(wrapper)
  end

  # Overrides the key collapse dropped, newest first: [{ key:, text: }].
  def dropped_ai_prompt_overrides
    DebugLogEntry.where(family: self, category: DROPPED_CATEGORY).order(created_at: :desc)
                 .map { { key: _1.metadata["key"], text: _1.metadata["text"] } }
  end

  def clear_dropped_ai_prompt_overrides = DebugLogEntry.where(family: self, category: DROPPED_CATEGORY).delete_all

  private
    def validate_ai_prompt_overrides_schema
      unless ai_prompt_overrides.is_a?(Hash)
        errors.add(:ai_prompt_overrides, :invalid)
        return
      end

      unknown_keys = ai_prompt_overrides.keys.map(&:to_s) - KEYS.map(&:to_s)
      if unknown_keys.any?
        errors.add(:ai_prompt_overrides, :invalid)
      end

      ai_prompt_overrides.each do |key, val|
        if val.nil?
          next
        elsif !val.is_a?(String)
          errors.add(:"ai_prompt_#{key}", :invalid)
        elsif val.include?("\u0000")
          errors.add(:"ai_prompt_#{key}", :invalid)
        end
      end
    end
end
